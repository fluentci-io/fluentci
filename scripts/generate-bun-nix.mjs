// Generate integrity-pinned fetchers for Bun2Nix without network access or Nix builds.
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const root = new URL("../", import.meta.url);
const lockText = await readFile(new URL("bun.lock", root), "utf8");
const lock = Bun.JSON5.parse(lockText);
const lockfileHash = new Bun.CryptoHasher("sha256")
  .update(lockText)
  .digest("hex");
const packages = new Map();
const nixString = (value) => JSON.stringify(value).replaceAll("${", "\\${");
for (const entry of Object.values(lock.packages)) {
  const identity = entry[0];
  if (identity.includes("@workspace:")) continue;
  const index = identity.lastIndexOf("@");
  const name = identity.slice(0, index);
  const version = identity.slice(index + 1);
  const hash = entry.at(-1);
  if (
    entry[1] !== "" ||
    !/^(@[^/]+\/)?[^/@]+$/.test(name) ||
    !/^[\w.+-]+$/.test(version) ||
    !/^sha(256|384|512)-[\w+/=]+$/.test(hash)
  ) {
    throw new Error(
      `Unsupported lock entry ${identity}; extend the generator before updating Nix dependencies.`,
    );
  }
  const url = `https://registry.npmjs.org/${name}/-/${name.split("/").at(-1)}-${version}.tgz`;
  const previous = packages.get(identity);
  if (previous && previous.hash !== hash)
    throw new Error(`Conflicting integrity for ${identity}`);
  packages.set(identity, { url, hash });
}
const output = [
  "# Generated by bun scripts/generate-bun-nix.mjs; do not edit.",
  "{ fetchurl }: {",
  `  lockfileHash = ${nixString(lockfileHash)};`,
  ...[...packages.entries()]
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
    .map(
      ([identity, { url, hash }]) =>
        `  ${nixString(identity)} = fetchurl {\n    url = ${nixString(url)};\n    hash = ${nixString(hash)};\n  };`,
    ),
  "}",
  "",
].join("\n");
const destination = new URL("nix/bun-deps.nix", root);
if (process.argv.includes("--check")) {
  if ((await readFile(destination, "utf8")) !== output)
    throw new Error(
      "nix/bun-deps.nix is stale; run bun scripts/generate-bun-nix.mjs",
    );
} else {
  await writeFile(destination, output);
  console.log(
    `Wrote ${packages.size} integrity-pinned packages to ${fileURLToPath(destination)}`,
  );
}
