#!/usr/bin/env python3
"""Stream FluentCI setup logs and persist validated exports for Spindle steps."""

import importlib.util
import json
import os
from pathlib import Path
import re
import shlex
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[2]
spec = importlib.util.spec_from_file_location("github_setup_env", ROOT / ".github/scripts/export-setup-env.py")
bridge = importlib.util.module_from_spec(spec)
spec.loader.exec_module(bridge)


def validate(values):
    for name, value in values.items():
        if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", name):
            raise ValueError("Invalid setup environment variable name")
        if name.startswith(("TANGLED_", "SPINDLE_", "FLUENTCI_SPINDLE_", "GITHUB_", "RUNNER_")) or name in {"BASH_ENV", "ENV", "SHELLOPTS", "BASHOPTS", "NODE_OPTIONS"}:
            raise ValueError("Setup cannot replace reserved runner variables")
        if not isinstance(value, str) or "\0" in value:
            raise ValueError("Invalid setup environment value")


def export(result, environ, state):
    # Reuse the existing bridge's typed-result, PATH, and variable validation.
    with tempfile.TemporaryDirectory() as temporary:
        paths = Path(temporary) / "paths"
        bridge.export(result, {**environ, "GITHUB_PATH": str(paths), "GITHUB_ENV": str(Path(temporary) / "env")})
        additions = list(reversed(paths.read_text().splitlines()))
    values = {item["name"]: item["value"] for item in result["environment"] if item["name"] != "PATH"}
    values["PATH"] = os.pathsep.join(dict.fromkeys([*additions, *environ.get("PATH", "").split(os.pathsep)]))
    validate(values)
    manifest = state / "environment.json"
    previous = json.loads(manifest.read_text()) if manifest.exists() else {}
    if not isinstance(previous, dict):
        raise ValueError("Invalid persisted setup environment")
    validate(previous)
    previous.update(values)
    state.mkdir(parents=True, exist_ok=True, mode=0o700)
    content = "# Generated by FluentCI setup; do not commit.\n" + "".join(f"export {name}={shlex.quote(value)}\n" for name, value in sorted(previous.items()))
    for destination, data in [(manifest, json.dumps(previous)), (state / "environment.sh", content)]:
        with tempfile.NamedTemporaryFile(mode="w", dir=state, delete=False, encoding="utf-8") as output:
            temporary = Path(output.name)
            try:
                os.chmod(temporary, 0o600)
                output.write(data)
                output.flush()
                os.replace(temporary, destination)
            finally:
                temporary.unlink(missing_ok=True)


def main():
    try:
        result = bridge.stream_result(sys.stdin, sys.stderr)
        export(result, os.environ, ROOT / ".tangled-state")
        print(f"Configured {result.get('tool', 'tool')} {result.get('version', '')}", file=sys.stderr)
    except (ValueError, KeyError, TypeError, AttributeError, OSError) as error:
        sys.exit(f"Could not export Spindle setup environment: {error}")


if __name__ == "__main__":
    main()
